export function iconSvg(name) {
  const rows = ICONS[name];
  if (!rows) return '';
  let rects = '';
  rows.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === '1') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    else if (c === '2') rects += `<rect x="${x}" y="${y}" width="1" height="1" opacity=".4"/>`;
  }));
  return `<svg class="px-ico" viewBox="0 0 8 8" fill="currentColor" aria-hidden="true">${rects}</svg>`;
}

export function applyIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    if (el.firstElementChild?.classList.contains('px-ico')) return;
    el.insertAdjacentHTML('afterbegin', iconSvg(el.dataset.icon));
  });
}
